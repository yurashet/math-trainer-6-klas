  /* S1. Дзесятковы запіс. Разрады. */
  function dS1Place(d) {
    var cnt = d <= 4 ? 2 : (d <= 8 ? 3 : 4);
    var ip = ri(1, d <= 4 ? 9 : 99);
    var ds = '';
    for (var i = 0; i < cnt; i++) ds += ri(0, 9);
    var names = ['дзясятых', 'сотых', 'тысячных', 'дзесяцітысячных'];
    var idx = ri(0, cnt - 1);
    if (Math.random() < 0.3) {
      var dig = ri(1, 9), guard = 0;
      while (ds.indexOf(String(dig)) !== -1 && guard++ < 30) dig = dig % 9 + 1;
      ds = ds.substring(0, idx) + dig + ds.substring(idx + 1);
      return {
        q: `У ліку ${ip + ',' + ds} лічба ${dig} стаіць у разрадзе з нумарам … (дзясятыя — 1, сотыя — 2, тысячная — 3, дзесяцітысячныя — 4)`,
        a: idx + 1,
        hint: 'Пасля коскі разрады ідуць злева направа: дзясятыя, сотыя, тысячная, дзесяцітысячныя.'
      };
    }
    return {
      q: `Якая лічба ў разрадзе ${names[idx]} у ліку ${ip + ',' + ds}?`,
      a: Number(ds.charAt(idx)),
      hint: 'Пасля коскі: дзясятыя, сотыя, тысячная, дзесяцітысячныя.'
    };
  }
  function dS1Frac(d) {
    if (Math.random() < 0.5) {
      /* AC-3: у decimals:S1 адказ — не больш за 2 знакі пасля коскі,
         таму назоўнікі толькі 10 і 100 (матрыца §4.1: dec_s1_frac_to_dec). */
      var den = d >= 6 ? 100 : 10, n = ri(1, den - 1);
      return {
        q: `Запішы дроб ${n}/${den} дзесятковым дробам.`,
        a: r2(n / den),
        hint: 'Колькі нулёў у назоўніку — столькі знакаў пасля коскі.'
      };
    }
    var wh = ri(1, d <= 5 ? 20 : 99), den2 = pick([10, 100]), n2 = ri(1, den2 - 1);
    return {
      q: `Запішы дзесятковым дробам: ${wh} цэлых ${n2} ${den2 === 10 ? 'дзясятых' : 'сотых'}.`,
      a: r3(wh + n2 / den2),
      hint: 'Цэлая частка — да коскі, дробная — пасля яе.'
    };
  }
